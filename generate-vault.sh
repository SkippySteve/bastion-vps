#!/bin/bash
# Generate group_vars/all/vault.yml with secrets that satisfy preflight validation.
# Encrypt the result before use:
#   uv run ansible-vault encrypt group_vars/all/vault.yml
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: generate-vault.sh [-o PATH]

Write a populated vault.yml for this playbook. Random secrets are generated
automatically; you are prompted for the ops sudo password, bootstrap web
password, and contact email addresses.

Requires: openssl, htpasswd (apache2-utils on Debian, httpd-tools on RHEL)

Options:
  -o PATH   Output file (default: group_vars/all/vault.yml)
  -h        Show this help
EOF
}

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
output_path="${script_dir}/group_vars/all/vault.yml"

while getopts ':ho:' opt; do
  case "$opt" in
    h)
      usage
      exit 0
      ;;
    o)
      output_path="$OPTARG"
      ;;
    *)
      usage >&2
      exit 1
      ;;
  esac
done

for cmd in openssl htpasswd; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "error: required command not found: $cmd" >&2
    if [ "$cmd" = htpasswd ]; then
      echo "Install apache2-utils (Debian) or httpd-tools (Fedora/RHEL)." >&2
    fi
    exit 1
  fi
done

rand_hex_32() {
  openssl rand -hex 32
}

rand_base64_token() {
  openssl rand -base64 60 | tr -d '\n'
}

rand_app_password() {
  openssl rand -base64 24 | tr -d '\n=+/'
}

generate_wazuh_password() {
  local specials='.*+?-'
  local upper lower digit special rest
  upper="$(openssl rand -base64 6 | tr -dc 'A-Z' | head -c 2)"
  lower="$(openssl rand -base64 6 | tr -dc 'a-z' | head -c 2)"
  digit="$(openssl rand -base64 6 | tr -dc '0-9' | head -c 2)"
  special="${specials:$((RANDOM % ${#specials})):1}"
  rest="$(openssl rand -base64 18 | tr -dc 'A-Za-z0-9.*+?-' | head -c 20)"
  printf '%s' "${upper}${lower}${digit}${special}${rest}"
}

wazuh_bcrypt_hash() {
  printf '%s' "$1" | htpasswd -inBC 12 '' | cut -d: -f2
}

prompt_nonempty() {
  local prompt="$1"
  local value
  while true; do
    read -rsp "$prompt" value
    echo
    if [ -n "$value" ]; then
      printf '%s' "$value"
      return 0
    fi
    echo "A value is required." >&2
  done
}

prompt_email() {
  local prompt="$1"
  local value
  while true; do
    read -rp "$prompt" value
    if printf '%s' "$value" | grep -Eq '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'; then
      printf '%s' "$value"
      return 0
    fi
    echo "Enter a valid email address." >&2
  done
}

yaml_quote() {
  local value="$1"
  value="${value//\'/\'\'}"
  printf "'%s'" "$value"
}

echo "Generating random database and application secrets..." >&2

authentik_postgresql_password="$(rand_hex_32)"
signoz_postgresql_password="$(rand_hex_32)"
scrapecast_db_password="$(rand_hex_32)"
scrapecast_secrets_encryption_key="$(openssl rand -base64 32 | tr -d '\n')"
authentik_secret_key="$(rand_base64_token)"
authentik_bootstrap_token="$(rand_base64_token)"
forgejo_secret_key="$(rand_base64_token)"
forgejo_internal_token="$(rand_base64_token)"
authentik_bootstrap_password="$(rand_app_password)"
forgejo_admin_password="$(rand_app_password)"

wazuh_indexer_admin_password="$(generate_wazuh_password)"
wazuh_dashboard_service_password="$(generate_wazuh_password)"
wazuh_api_password="$(generate_wazuh_password)"

wazuh_indexer_admin_hash="$(wazuh_bcrypt_hash "$wazuh_indexer_admin_password")"
wazuh_dashboard_service_hash="$(wazuh_bcrypt_hash "$wazuh_dashboard_service_password")"

echo "Enter the secrets you will need to remember:" >&2
ops_password="$(prompt_nonempty 'ops sudo password: ')"
admin_password_hash="$(printf '%s' "$ops_password" | openssl passwd -6 -stdin | awk '/^\$/ { print; exit }')"
unset ops_password

web_bootstrap_password="$(prompt_nonempty 'temporary web bootstrap password: ')"
bootstrap_admin_htpasswd="$(printf '%s' "$web_bootstrap_password" | htpasswd -inBC 12 bootstrap)"
unset web_bootstrap_password

acme_email="$(prompt_email 'ACME contact email: ')"
authentik_bootstrap_email="$(prompt_email 'Authentik bootstrap admin email: ')"
forgejo_admin_email="$(prompt_email 'Forgejo admin email: ')"
forgejo_admin_user="forgeadmin"

tmp_file="$(mktemp "${output_path}.XXXXXX")"
trap 'rm -f "$tmp_file"' EXIT

cat >"$tmp_file" <<EOF
---
# Generated by generate-vault.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Encrypt before use: uv run ansible-vault encrypt group_vars/all/vault.yml

admin_password_hash: $(yaml_quote "$admin_password_hash")

acme_email: $(yaml_quote "$acme_email")
bootstrap_admin_htpasswd: $(yaml_quote "$bootstrap_admin_htpasswd")

authentik_postgresql_password: $(yaml_quote "$authentik_postgresql_password")
authentik_secret_key: $(yaml_quote "$authentik_secret_key")
authentik_bootstrap_password: $(yaml_quote "$authentik_bootstrap_password")
authentik_bootstrap_token: $(yaml_quote "$authentik_bootstrap_token")
authentik_bootstrap_email: $(yaml_quote "$authentik_bootstrap_email")

forgejo_secret_key: $(yaml_quote "$forgejo_secret_key")
forgejo_internal_token: $(yaml_quote "$forgejo_internal_token")
forgejo_admin_user: $(yaml_quote "$forgejo_admin_user")
forgejo_admin_password: $(yaml_quote "$forgejo_admin_password")
forgejo_admin_email: $(yaml_quote "$forgejo_admin_email")

signoz_postgresql_password: $(yaml_quote "$signoz_postgresql_password")

scrapecast_db_password: $(yaml_quote "$scrapecast_db_password")
scrapecast_secrets_encryption_key: $(yaml_quote "$scrapecast_secrets_encryption_key")
# Packages:read token for svc-scrapecast. Create it in Forgejo after the
# scrapecast repo exists, then:
#   uv run ansible-vault edit group_vars/all/vault.yml
# scrapecast_registry_pull_token: ''

wazuh_indexer_admin_password: $(yaml_quote "$wazuh_indexer_admin_password")
wazuh_indexer_admin_hash: $(yaml_quote "$wazuh_indexer_admin_hash")
wazuh_dashboard_service_password: $(yaml_quote "$wazuh_dashboard_service_password")
wazuh_dashboard_service_hash: $(yaml_quote "$wazuh_dashboard_service_hash")
wazuh_api_password: $(yaml_quote "$wazuh_api_password")

# Optional Cloudflare. Uncomment and fill when cloudflare_dns_enabled is
# true, or when traefik_acme_challenge is dns. Prefer a scoped API token.
# cloudflare_api_token: ''
# cloudflare_api_key: ''
# cloudflare_email: ''
EOF

install -d -m 700 "$(dirname "$output_path")"
mv "$tmp_file" "$output_path"
chmod 600 "$output_path"
trap - EXIT

cat >&2 <<EOF

Wrote ${output_path}

Save these generated application passwords (not stored elsewhere):

  authentik_bootstrap_password: ${authentik_bootstrap_password}
  forgejo_admin_password:       ${forgejo_admin_password}
  wazuh_indexer_admin_password: ${wazuh_indexer_admin_password}
  wazuh_dashboard_service_password: ${wazuh_dashboard_service_password}
  wazuh_api_password:           ${wazuh_api_password}

Add scrapecast_registry_pull_token to the vault after you create a
packages:read token in Forgejo.

Next step:
  uv run ansible-vault encrypt ${output_path}
EOF
